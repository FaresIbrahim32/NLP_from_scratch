import re

from datasets import load_dataset

ds = load_dataset("Salesforce/wikitext", "wikitext-103-v1")

def clean_line(line):
    line = line.strip()
    if not line or line.startswith("="):              # skip empty lines and section headers
        return None

    line = line.replace("<unk>", " <UNK> ")
    line = re.sub(r"\s@-@\s", " ", line)              # hyphenated words -> two words
    line = re.sub(r"\s@[,.]@\s", "", line)            # number artifacts (digits get stripped anyway)
    line = line.lower().replace("<unk>", "<unk>")

    # split the text into sentences first, so we can drop ones containing <unk>
    sentences = re.split(r"\s*[.!?;:]+\s+", line)
    out = []
    for s in sentences:
        if "<unk>" in s:                              # drop whole sentence if it has an unknown word
            continue
        s = re.sub(r"[-–—_/]", " ", s)                # split any remaining hyphens/slashes
        s = re.sub(r"\s+n't\b", "", s)                # "did n't" -> "did"
        s = re.sub(r"\s+'(s|re|ve|ll|d|m)\b", "", s)  # possessives/contractions: "cat 's" -> "cat"
        s = re.sub(r"[^a-z ]", "", s)                 # keep only letters and spaces
        s = re.sub(r"\s+", " ", s).strip()
        if len(s.split()) >= 3:                       # skip tiny fragments
            out.append(s + ".")
    return " ".join(out) if out else None

def build_corpus(split, max_lines=None):
    cleaned = []
    for i, line in enumerate(ds[split]["text"]):
        if max_lines and i >= max_lines:
            break
        c = clean_line(line)
        if c:
            cleaned.append(c)
    return " ".join(cleaned)

corpus = build_corpus("train", max_lines=50_000)     # remove max_lines for the full ~100M words
with open("corpus.txt", "w") as f:
    f.write(corpus)
print(len(corpus.split()), "words")

def tokenize(text):
  return re.findall(r'\w+|[^\w\s]', text)

words = tokenize(corpus.lower())

def build_bigrams(words):
  lst = []
  for w in range(len(words)-1):
    bigram = words[w] + ' ' + words[w + 1]
    lst.append(bigram)
  return lst

bigram_list = build_bigrams(words)
print('Total bigrams:', len(bigram_list))
print('First 20 bigrams:', bigram_list[:20])

def build_counts(words):
  counts ={}
  for w in range(len(words)-2):
    bigram = words[w] + ' ' + words[w + 1]
    next_token = words[w + 2]
    if bigram not in counts:
      counts[bigram] = {}
    counts[bigram][next_token] = counts[bigram].get(next_token, 0) + 1
  return counts

counts = build_counts(words)

print(counts['the battlefield'])

def prediction(context):
  context = tokenize(context.lower())

  bigram = context[-2] + ' ' + context[-1]

  if bigram not in counts:
    return None
  best_count = 0
  best_token = None
  for token , count in counts[bigram].items():
    if count > best_count:
      best_count = count
      best_token = token
  return best_token

print(prediction('He did'))

def autocomplete(context):
  num_tokens = 10
  res = context.lower()
  for i in range(num_tokens):
    nxt = prediction(res)
    if nxt is not None:

      seq = res + ' ' + nxt
      print(seq)
      seq = tokenize(seq.lower())
      res = seq[-2] + ' ' + seq[-1]
    else:
      print('sorry this was out of corpus')
      break

autocomplete('He did')
